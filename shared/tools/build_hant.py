#!/usr/bin/env python3
"""Build kog-hant.js: a compact Simplified -> Traditional table for the shared menu script.

Source data: OpenCC (Apache 2.0) dictionaries STPhrases, STCharacters and TWVariants,
i.e. the same result as OpenCC's "s2tw" (Taiwan-standard character forms, no vocabulary swaps).
Phrases that convert differently from plain character-by-character conversion are kept with
their target; phrases needed only to keep longest-match segmentation identical are kept as
source text alone. Glossary overrides are applied last.

Run:  python3 build_hant.py <glossary.json> <out kog-hant.js>
"""
import json, os, sys
import opencc

D = os.path.join(os.path.dirname(opencc.__file__), "dictionary")

def load(name):
    out = {}
    with open(os.path.join(D, name), encoding="utf-8") as f:
        for line in f:
            line = line.rstrip("\n")
            if not line or "\t" not in line: continue
            k, v = line.split("\t", 1)
            out[k] = v.split(" ")[0]
    return out

ST_CHARS, ST_PHRASES, TW_VAR = load("STCharacters.txt"), load("STPhrases.txt"), load("TWVariants.txt")
gloss = json.load(open(sys.argv[1], encoding="utf-8"))
# House character forms: where the dictionary's choice is not the one this church writes (講台 not 講臺).
HOUSE = {v["from"]: v["to"] for v in gloss.get("hant_variants", [])}
def tw(s):
    s = "".join(TW_VAR.get(c, c) for c in s)
    return "".join(HOUSE.get(c, c) for c in s)

char_map = {}
for c, t in ST_CHARS.items():
    t = tw(t)
    if t != c: char_map[c] = t
for c, t in TW_VAR.items():            # Traditional-but-not-Taiwan forms that may already be in the text
    if c not in ST_CHARS and tw(t) != c: char_map.setdefault(c, tw(t))
for c, t in HOUSE.items():
    if c not in ST_CHARS: char_map[c] = t

char_map = {c: t for c, t in char_map.items() if ord(c) < 0x10000 and len(t) == 1 and ord(t) < 0x10000}
default = lambda s: "".join(char_map.get(c, c) for c in s)
import re
HAN_ONLY = re.compile(r"^[\u2e80-\u9fff\uf900-\ufaff]+$")

phrases = {p: tw(t) for p, t in ST_PHRASES.items() if len(p) > 1 and HAN_ONLY.match(p) and all(ord(c) < 0x10000 for c in tw(t))}
exceptions = {p: t for p, t in phrases.items() if t != default(p)}

# Every other phrase converts the default way, but is still needed so that the longest phrase is
# matched first (the same segmentation as the reference converter). Only its source text is stored.
protect = [p for p in phrases if p not in exceptions]

overrides = {o["hans"]: o["hant"] for o in gloss.get("hant_overrides", [])}

table = dict(exceptions); table.update(overrides)
protect = sorted(p for p in protect if p not in table)

cs = "".join(char_map.keys()); ct = "".join(char_map[c] for c in char_map)
assert len(cs) == len(ct), "astral characters would need code-point arrays"
ph = "|".join(f"{k}={v}" for k, v in sorted(table.items()))
pq = "|".join(protect)
js = ("/* kog-hant.js - Simplified to Traditional table for kog-shell.js. GENERATED by tools/build_hant.py; do not edit.\n"
      "   Derived from OpenCC dictionaries (https://github.com/BYVoid/OpenCC, Apache License 2.0), s2tw forms,\n"
      "   plus the overrides in kog-glossary.json. */\n"
      "(function(){var K=window.KOG=window.KOG||{};K._hantData={s:%s,t:%s,p:%s,q:%s};if(K._hantLoaded)K._hantLoaded();})();\n"
      % (json.dumps(cs, ensure_ascii=False), json.dumps(ct, ensure_ascii=False), json.dumps(ph, ensure_ascii=False), json.dumps(pq, ensure_ascii=False)))
open(sys.argv[2], "w", encoding="utf-8").write(js)
json.dump({"chars": char_map, "phrases": table, "protect": protect}, open(os.path.splitext(sys.argv[2])[0] + ".table.json", "w", encoding="utf-8"), ensure_ascii=False)
print(f"house forms {len(HOUSE)}  chars {len(char_map)}  exceptions {len(exceptions)}  protective {len(protect)}  overrides {len(overrides)}  -> {len(js.encode('utf-8'))/1024:.0f} KB")
